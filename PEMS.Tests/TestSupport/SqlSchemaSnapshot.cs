using System.Security.Cryptography;
using System.Text;
using System.Text.RegularExpressions;
using Microsoft.Data.SqlClient;

namespace PEMS.Tests.TestSupport;

/// <summary>
/// SCRUM-280: a comparable description of a database schema, one line per object, read from the SQL Server catalog.
/// Two databases built by different migration paths (fresh install vs upgrade from an old release) must give the same lines.
/// Deliberately ignored: column order (ALTER TABLE ADD appends), system-generated default-constraint names, and the
/// migration history / run-log contents (data, not schema).
/// Each query returns its parts as separate columns and C# joins them with '|': catalog views mix collations
/// (names vs. type descriptions), so concatenating them in SQL fails with a collation conflict.
/// </summary>
public static class SqlSchemaSnapshot
{
    private const string UserSchemas = "s.name NOT IN (N'sys', N'INFORMATION_SCHEMA', N'guest')";

    private static readonly string[] Queries =
    {
        // tables
        $@"SELECT 'T', s.name, t.name
           FROM sys.tables t JOIN sys.schemas s ON s.schema_id = t.schema_id WHERE {UserSchemas}",
        // columns
        $@"SELECT 'C', s.name, t.name, c.name, ty.name, c.max_length, c.precision, c.scale, c.is_nullable, c.is_identity,
                  c.collation_name, cc.definition
           FROM sys.columns c
           JOIN sys.tables t ON t.object_id = c.object_id JOIN sys.schemas s ON s.schema_id = t.schema_id
           JOIN sys.types ty ON ty.user_type_id = c.user_type_id
           LEFT JOIN sys.computed_columns cc ON cc.object_id = c.object_id AND cc.column_id = c.column_id
           WHERE {UserSchemas}",
        // indexes, primary keys and unique constraints (key columns in order, then included columns)
        $@"SELECT 'I', s.name, t.name, i.name, i.type_desc, i.is_unique, i.is_primary_key, i.filter_definition,
                  STUFF((SELECT ',' + c.name + CASE WHEN ic.is_descending_key = 1 THEN ' DESC' ELSE '' END
                         FROM sys.index_columns ic JOIN sys.columns c ON c.object_id = ic.object_id AND c.column_id = ic.column_id
                         WHERE ic.object_id = i.object_id AND ic.index_id = i.index_id AND ic.is_included_column = 0
                         ORDER BY ic.key_ordinal FOR XML PATH('')), 1, 1, ''),
                  STUFF((SELECT ',' + c.name
                         FROM sys.index_columns ic JOIN sys.columns c ON c.object_id = ic.object_id AND c.column_id = ic.column_id
                         WHERE ic.object_id = i.object_id AND ic.index_id = i.index_id AND ic.is_included_column = 1
                         ORDER BY c.name FOR XML PATH('')), 1, 1, '')
           FROM sys.indexes i JOIN sys.tables t ON t.object_id = i.object_id JOIN sys.schemas s ON s.schema_id = t.schema_id
           WHERE {UserSchemas} AND i.type > 0",
        // foreign keys
        $@"SELECT 'F', s.name, t.name, fk.name, rs.name, rt.name,
                  STUFF((SELECT ',' + pc.name + '>' + rc.name
                         FROM sys.foreign_key_columns k
                         JOIN sys.columns pc ON pc.object_id = k.parent_object_id AND pc.column_id = k.parent_column_id
                         JOIN sys.columns rc ON rc.object_id = k.referenced_object_id AND rc.column_id = k.referenced_column_id
                         WHERE k.constraint_object_id = fk.object_id ORDER BY k.constraint_column_id FOR XML PATH('')), 1, 1, ''),
                  fk.delete_referential_action_desc, fk.update_referential_action_desc, fk.is_not_trusted, fk.is_disabled
           FROM sys.foreign_keys fk
           JOIN sys.tables t ON t.object_id = fk.parent_object_id JOIN sys.schemas s ON s.schema_id = t.schema_id
           JOIN sys.tables rt ON rt.object_id = fk.referenced_object_id JOIN sys.schemas rs ON rs.schema_id = rt.schema_id
           WHERE {UserSchemas}",
        // check constraints
        $@"SELECT 'K', s.name, t.name, ck.name, ck.definition, ck.is_not_trusted, ck.is_disabled
           FROM sys.check_constraints ck JOIN sys.tables t ON t.object_id = ck.parent_object_id JOIN sys.schemas s ON s.schema_id = t.schema_id
           WHERE {UserSchemas}",
        // default values (by column; the constraint name is often generated by SQL Server)
        $@"SELECT 'D', s.name, t.name, c.name, dc.definition
           FROM sys.default_constraints dc
           JOIN sys.columns c ON c.object_id = dc.parent_object_id AND c.column_id = dc.parent_column_id
           JOIN sys.tables t ON t.object_id = dc.parent_object_id JOIN sys.schemas s ON s.schema_id = t.schema_id
           WHERE {UserSchemas}",
        // views, procedures, functions, triggers (definition hashed after whitespace normalisation, in C#)
        $@"SELECT 'M', o.type_desc, s.name, o.name, m.definition
           FROM sys.sql_modules m JOIN sys.objects o ON o.object_id = m.object_id JOIN sys.schemas s ON s.schema_id = o.schema_id
           WHERE {UserSchemas} AND o.is_ms_shipped = 0",
        // full-text indexes (only when the feature is installed)
        $@"SELECT 'X', s.name, t.name,
                  STUFF((SELECT ',' + c.name FROM sys.fulltext_index_columns fc
                         JOIN sys.columns c ON c.object_id = fc.object_id AND c.column_id = fc.column_id
                         WHERE fc.object_id = fi.object_id ORDER BY c.name FOR XML PATH('')), 1, 1, '')
           FROM sys.fulltext_indexes fi JOIN sys.tables t ON t.object_id = fi.object_id JOIN sys.schemas s ON s.schema_id = t.schema_id
           WHERE {UserSchemas}"
    };

    public static async Task<SortedSet<string>> ReadAsync(string connectionString)
    {
        var lines = new SortedSet<string>(StringComparer.Ordinal);
        await using var conn = new SqlConnection(connectionString);
        await conn.OpenAsync();
        foreach (var sql in Queries)
        {
            await using var cmd = conn.CreateCommand();
            cmd.CommandText = sql;
            await using var reader = await cmd.ExecuteReaderAsync();
            while (await reader.ReadAsync())
            {
                var parts = new string[reader.FieldCount];
                for (var i = 0; i < parts.Length; i++)
                    parts[i] = reader.IsDBNull(i) ? "" : Convert.ToString(reader.GetValue(i), System.Globalization.CultureInfo.InvariantCulture)!;
                lines.Add(Line(parts));
            }
        }
        return lines;
    }

    /// <summary>Module bodies become a hash of their whitespace-normalised text so a diff stays readable.</summary>
    private static string Line(string[] parts)
    {
        if (parts[0] != "M") return string.Join('|', parts);
        var body = Regex.Replace(parts[4], @"\s+", " ").Trim();
        var hash = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(body)))[..16];
        return $"M|{parts[1]}|{parts[2]}.{parts[3]}|{hash}";
    }

    /// <summary>Readable difference ("- only in expected", "+ only in actual"), empty when equal.</summary>
    public static IReadOnlyList<string> Diff(SortedSet<string> expected, SortedSet<string> actual)
        => expected.Except(actual).Select(l => "- " + l)
            .Concat(actual.Except(expected).Select(l => "+ " + l))
            .OrderBy(l => l[2..], StringComparer.Ordinal)
            .ToList();
}
